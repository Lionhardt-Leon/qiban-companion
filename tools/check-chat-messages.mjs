import assert from 'node:assert/strict';
import {nativeMessageID,reconcileMessages,decorateIdentities} from '../chat-adapter/identity.js';
import {editMessage,deleteMessage,regenerationPlan,applyRegenerated,invalidateMessageMemory,restrictMemoryReferences,createDraft,keepDraft,endDraft} from '../chat-adapter/message-ops.js';

const card='char_test',nativeID=await nativeMessageID(card,'msg_one');
const user={id:'msg_one',role:'user',speakerName:'分析员',text:'你好',createdAt:1,meta:{qibanSpokenChinese:'旧台词'},attachments:[{id:'pic',type:'image',dataRef:'idb-media:test'},{source:'tts-reply',type:'audio'}]};
const counterpart={...user,id:nativeID,speakerName:'秦天',attachments:[],meta:{}};
const original={characters:[{id:card}],conversations:[{id:'private:test',type:'private',memberIds:[card]}],messages:{'private:test':[user,{id:'a1',role:'assistant',text:'你好呀',createdAt:2,speakerId:card,meta:{}},{id:'u2',role:'user',text:'接着聊',createdAt:3,meta:{}}]}};
let checks=0;
function check(action){action();checks++;}
const repair=await reconcileMessages([user,counterpart],card);
check(()=>assert.equal(repair.messages.length,1));
check(()=>assert.equal(repair.messages[0].id,user.id));
check(()=>assert.equal(repair.messages[0].attachments.length,2));
check(()=>assert.equal(repair.messages[0].meta.qibanNativeId,nativeID));
const repeat=await reconcileMessages([user,{...user,id:'msg_two'}],card);
check(()=>assert.equal(repeat.messages.length,2,'legitimate repeated text is not a duplicate identity'));
check(()=>assert.equal(repair.nativeIDs.msg_one,nativeID));
const decorated=decorateIdentities(original,{[card]:{qibanId:'native-card',nativeIDs:{msg_one:nativeID}}},'秦天');
check(()=>assert.equal(decorated.messages['private:test'][0].speakerName,'秦天'));
check(()=>assert.equal(decorated.messages['private:test'][0].meta.qibanNativeId,nativeID));
check(()=>assert.equal(decorated.characters[0].qibanId,'native-card'));
check(()=>assert.equal(original.messages['private:test'][0].speakerName,'分析员','decoration does not mutate the live producer snapshot'));
const edited=editMessage(original,'private:test','msg_one','我喜欢你');
check(()=>assert.equal(edited.messages['private:test'][0].text,'我喜欢你'));
check(()=>assert.equal(edited.messages['private:test'][0].id,user.id));
check(()=>assert.equal(edited.messages['private:test'][0].meta.qibanSpokenChinese,undefined));
check(()=>assert.equal(edited.messages['private:test'][0].attachments.length,1));
check(()=>assert.equal(edited.messages['private:test'][1].text,'你好呀'));
const plan=regenerationPlan(edited,'private:test','msg_one');
check(()=>assert.equal(plan.user.text,'我喜欢你','regeneration uses the saved edit'));
check(()=>assert.deepEqual(plan.history.map(item=>item.id),['msg_one']));
check(()=>assert.equal(plan.target.id,'a1'));
const aiPlan=regenerationPlan(edited,'private:test','a1');
check(()=>assert.deepEqual(aiPlan.history.map(item=>item.id),['msg_one'],'old AI reply and later conversation are not model input'));
const applied=applyRegenerated(edited,'private:test',aiPlan,{...aiPlan.target,text:'新的回答'});
check(()=>assert.equal(applied.messages['private:test'].length,3));
check(()=>assert.equal(applied.messages['private:test'][1].text,'新的回答'));
check(()=>assert.equal(applied.messages['private:test'][2].text,'接着聊','later history is retained'));
const aiEdited=editMessage(original,'private:test','a1','我自己修改的回答');
check(()=>assert.equal(regenerationPlan(aiEdited,'private:test','u2').history[1].text,'我自己修改的回答','subsequent context uses edited AI text'));
check(()=>assert.equal(deleteMessage(original,'private:test','msg_one').messages['private:test'].length,2));
check(()=>assert.equal(original.messages['private:test'].length,3));
const memory={memories:[{id:'derived',source:'daily',sourceMessageIds:['msg_one','a1']},{id:'other',source:'daily',sourceMessageIds:['u2']},{id:'manual',source:'manual',sourceMessageIds:['msg_one']}],edges:[{id:'edge',sourceMemoryIds:['derived']}],deletedIds:[]};
const cleaned=invalidateMessageMemory(memory,['msg_one']);
check(()=>assert.deepEqual(cleaned.memories.map(item=>item.id),['other','manual']));
check(()=>assert.equal(cleaned.edges.length,0));
check(()=>assert.ok(cleaned.deletedIds.includes('derived')));
const projected=restrictMemoryReferences(memory,memory,['msg_one','a1']);
check(()=>assert.deepEqual(projected.memories.map(item=>item.id),['derived','manual'],'future-derived memories cannot enter an earlier regeneration'));
check(()=>assert.equal(projected.edges.length,1));
check(()=>assert.equal(restrictMemoryReferences(memory,memory,null),memory,'normal conversations keep their full memory routing'));
const draft=createDraft(original,'private:test',plan.history),normalized={};
check(()=>assert.equal(keepDraft(draft,normalized),true));
check(()=>assert.equal(keepDraft({__qibanDraft:'unregistered'},{}),false));
check(()=>assert.equal(draft.messages['private:test'].length,1));
endDraft(draft);check(()=>assert.equal(keepDraft(draft,{}),false));
console.log(JSON.stringify({focusedChatMessageChecks:checks,passed:true,noNetwork:true}));
